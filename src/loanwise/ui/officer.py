def render(svc: state.Services, user) -> None:
    theme.inject("officer")
    token = st.session_state["token"]
    st.session_state.setdefault(NAV_KEY, PAGES[0])
    with st.sidebar:
        ui.html('<div class="lw-brand">LoanWise</div><div style="font-size:.78rem;letter-spacing:.14em">RISK &amp; REVIEW CONSOLE</div>')
        st.write("")
        st.radio("Navigation", PAGES, key=NAV_KEY, label_visibility="collapsed")
